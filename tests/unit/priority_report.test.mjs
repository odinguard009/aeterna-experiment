// v0.60.3 (owner, 2026-10-18): card priority report and the Fandom data gaps (Nexus levels, Ultimate Trigger lines).
// The tables in data/sources are not in the light clone; tests that read them skip there (like I30 and B60-12).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/game.mjs';

const py = (code) => JSON.parse(execFileSync('python3', ['-c', `import sys, json; sys.path.insert(0, 'tools'); import import_fandom as m\n${code}`], { cwd: ROOT, encoding: 'utf8' }));
const NO_SRC = !existsSync(join(ROOT, 'data/sources/fandom-nexus-levels.tsv')) && 'data/sources not checked out (light clone)';
const staged = () => readdirJson('data/import').flat();
function readdirJson(dir) {
  return execFileSync('python3', ['-c', `import glob, json; print(json.dumps([json.load(open(f, encoding='utf-8')) for f in sorted(glob.glob('${dir}/saga-[0-9][0-9].json'))]))`], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20 })
    .trim().split('\n').map(JSON.parse)[0];
}

test('P603-01 ut_params fixes the wiki typos of the level brackets', () => {
  const r = py(`print(json.dumps([m.ut_params(x) for x in ['LV4][LV5] (When Attacks)', '[V3][LV4][LV5] (When Attacks)', '[LV4] (When Attacks)']]))`);
  assert.deepEqual(r, ['[LV4][LV5] (When Attacks)', '[LV3][LV4][LV5] (When Attacks)', '[LV4] (When Attacks)']);
});

test('P603-02 add_ut_lines writes the level/timing back after each bare Ultimate Trigger head, in order', () => {
  const r = py(`print(json.dumps(m.add_ut_lines('X\\n\\nUltimate Trigger\\nWhen Ultimate Trigger hits, a.\\n\\nUltimate Trigger\\nWhen Ultimate Trigger hits, b.', ['[LV4] (When Attacks)', '[LV5] (When Blocks)'])))`);
  assert.equal(r, 'X\n\nUltimate Trigger [LV4] (When Attacks)\nWhen Ultimate Trigger hits, a.\n\nUltimate Trigger [LV5] (When Blocks)\nWhen Ultimate Trigger hits, b.');
});

test('P603-03 add_ut_lines leaves a head alone when the page gave fewer lines', () => {
  const r = py(`print(json.dumps(m.add_ut_lines('Ultimate Trigger\\nA.\\n\\nUltimate Trigger\\nB.', ['[LV4] (When Attacks)'])))`);
  assert.equal(r, 'Ultimate Trigger [LV4] (When Attacks)\nA.\n\nUltimate Trigger\nB.');
});

test('P603-04 the Nexus table has 1,375 pages and every value starts with a level', { skip: NO_SRC }, () => {
  const r = py(`t = m.nexus_table(); print(json.dumps([len(t), all(len(v) >= 1 for v in t.values()), sum(1 for v in t.values() if v[0] == 0)]))`);
  assert.equal(r[0], 1375); assert.equal(r[1], true); assert.ok(r[2] >= 1370, String(r[2]));
});

test('P603-05 the import report counts the filled gaps', () => {
  const s = JSON.parse(readFileSync(join(ROOT, 'data/import/report.json'), 'utf8')).stats;
  assert.ok(s.nexus_levels_added >= 600, String(s.nexus_levels_added));
  assert.ok(s.ut_lines_added >= 110, String(s.ut_lines_added));
});

test('P603-06 a staged Nexus keeps LV1 at 0 cores and has rising thresholds', () => {
  const nx = staged().filter(c => c.type === 'Nexus' && c.levels.length > 1);
  assert.ok(nx.length >= 600, String(nx.length));
  for (const c of nx) {
    assert.equal(c.levels[0].cores, 0, c.id);
    for (let i = 1; i < c.levels.length; i++) assert.ok(c.levels[i].cores > c.levels[i - 1].cores, c.id);
  }
});

test('P603-07 Ultimate-Cu-Sith carries its Ultimate Trigger level and timing', () => {
  const c = staged().find(x => x.name === 'Ultimate-Cu-Sith');
  assert.match(c.text, /Ultimate Trigger \[LV4\] \(When Attacks\)\nWhen Ultimate Trigger hits/);
});

test('P603-08 priority report: summary line and the Standard block A table', () => {
  const line = execFileSync('python3', ['tools/priority_report.py', '--line'], { cwd: ROOT, encoding: 'utf8' }).trim();
  assert.match(line, /^priority: Standard block A \d+ playable \/ \d+ in data \/ ~\d+ released; newest Eternal Saga \d+$/);
  const md = readFileSync(join(ROOT, 'docs/reports/priority-report.md'), 'utf8');
  assert.match(md, /^# Priority report \(generated by tools\/priority_report\.py; do not edit\)/);
  assert.match(md, /\| 26RBS01 \| 2026-04-18 \| 144 \|/);
  assert.match(md, /## 4\. Version marks are new cards, not reprints/);
});
