// Build and source layout (no browser): index.html must always be the exact build of its sources (packages/, apps/web/).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { buildParts, packBlob, codec, PACK_RE } from '../../tools/build.mjs';
import { codeMap } from '../../tools/code_map.mjs';
import { srcParts, SRC_DIRS } from '../../tools/src_parts.mjs';
import { ROOT } from './lib/game.mjs';

const rd = p => readFileSync(join(ROOT, p), 'utf8');
const parts = srcParts(ROOT).map(p => p.rel);

test('B01 index.html is the exact build of src/', () => {
  assert.equal(rd('index.html'), buildParts().html, 'run: node tools/build.mjs');
});
test('B02 every script part is named NN-name.js and the numbers are unique', () => {
  const all = SRC_DIRS.flatMap(d => readdirSync(join(ROOT, d)).filter(f => f.endsWith('.js')));
  assert.equal(all.length, parts.length, 'a .js file in a source folder is not a script part');
  const nums = parts.map(p => { const f = p.split('/').pop(); assert.match(f, /^\d\d[a-z]?-[a-z0-9-]+\.js$/); return f.split('-')[0]; });
  assert.equal(new Set(nums).size, nums.length);
});
test('B03 every script part is non-empty and ends with a newline', () => {
  for (const f of parts) { const s = rd(f); assert.ok(s.trim().length > 0, f); assert.ok(s.endsWith('\n'), f); }
});
test('B04 the empty pack marker appears exactly once in the script parts', () => {
  const n = parts.reduce((s, f) => s + rd(f).split('/*PACK_START*//*PACK_END*/').length - 1, 0);
  assert.equal(n, 1);
});
test('B05 no part keeps an embedded card pack (the build fills it from data/)', () => {
  for (const f of parts) assert.doesNotMatch(rd(f), /BUILTIN_PACK = \[/, f);
});
test('B06 the template has the CSS and JS markers once each and is a full page', () => {
  const t = rd('apps/web/index.template.html');
  assert.equal(t.split('/*@@CSS@@*/\n').length, 2); assert.equal(t.split('/*@@JS@@*/\n').length, 2);
  assert.match(t, /^<!DOCTYPE html>/i); assert.match(t, /<\/html>\n$/);
});
test('B07 the built page has the app <script> plus the early theme script and one <style> block', () => {
  const h = buildParts().html;
  assert.equal((h.match(/<script>/g) || []).length, 2); assert.equal((h.match(/<style>/g) || []).length, 1);
});
test('B08 VERSION is declared once and matches package.json', () => {
  const js = buildParts().js, m = js.match(/const VERSION = '([^']+)'/g) || [];
  assert.equal(m.length, 1);
  const v = m[0].match(/'([^']+)'/)[1];
  assert.equal(v, JSON.parse(rd('package.json')).version);
});
test('B09 packBlob escapes "</" so card text cannot close the script tag', () => {
  const b = packBlob([{ text: 'a</script><b>' }]);
  assert.ok(!b.includes('</')); assert.deepEqual(JSON.parse(b.replace(/<\\\//g, '</')), [{ text: 'a</script><b>' }]);
});
test('B10 the embedded pack holds every card of build/all-cards.json', () => {
  const cards = JSON.parse(rd('build/all-cards.json'));
  const h = buildParts().html, m = h.match(PACK_RE);
  assert.ok(m); assert.equal(codec().loadPack(m[1]).length, cards.length);
});
test('B11 the build is deterministic (two builds are identical)', () => {
  assert.equal(buildParts().html, buildParts().html);
});
test('B12 tools/embed_pack.py only delegates to the build (no second writer of index.html)', () => {
  const s = rd('tools/embed_pack.py');
  assert.match(s, /build\.mjs/); assert.doesNotMatch(s, /open\(p, 'w'\)/);
});
test('B13 docs/ai/code-map.md is current (generated by the build)', () => {
  assert.equal(rd('docs/ai/code-map.md'), codeMap(), 'run: node tools/build.mjs');
});
test('B14 every top-level name in the code map is listed once per part', () => {
  for (const sec of codeMap().split('\n## ').slice(1)) {
    const names = (sec.split('\n')[1] || '').split(', ').filter(Boolean);
    assert.equal(new Set(names).size, names.length, sec.split('\n')[0]);
  }
});
test('B15 no test or tool uses an absolute workspace path (must run on GitHub too)', () => {
  const walk = d => readdirSync(join(ROOT, d), { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(d + '/' + e.name) : [d + '/' + e.name]);
  const bad = ['tests', 'tools'].flatMap(walk).filter(f => /\.(py|mjs|js)$/.test(f) && f !== 'tests/unit/build.test.mjs' && rd(f).includes('/home/claude'));
  assert.deepEqual(bad, []);
});
