-- 0001_init.sql - accounts, decks, matches and the replay records (roadmap M7 step 1).
--
-- Shape follows what the game already produces, so nothing has to be invented:
--   * a deck slot is what packages/engine/src/04-decks.js stores locally (name, format, the
--     card-id -> count map, the Key Spirit, the sleeve picture);
--   * a match is what apps/server/src/host.mjs runs (a room, a format, a seed, both decks);
--   * a replay is a port record v2 (packages/engine/src/15b-replay.js): the seed, the decks and
--     every answered decision, which replays to the same log hash.
--
-- Accounts are optional on purpose (monorepo plan: guests may play), so a seat can carry a
-- display name instead of an account id.
--
-- Conventions: created_at/updated_at are timestamptz in UTC; ids are uuid v4 generated by the
-- application (the server) so no extension is required; every foreign key has an index.

BEGIN;

-- Accounts. Email and Discord id are both optional and unique when present: the plan allows
-- email magic links and Discord OAuth, and casual play needs no account at all.
CREATE TABLE IF NOT EXISTS accounts (
  id            uuid PRIMARY KEY,
  email         text UNIQUE,
  discord_id    text UNIQUE,
  display_name  text NOT NULL CHECK (length(display_name) BETWEEN 1 AND 40),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK (email IS NOT NULL OR discord_id IS NOT NULL)          -- an account must be reachable somehow
);
CREATE INDEX IF NOT EXISTS accounts_created_idx ON accounts (created_at);

-- Deck slots: the server-side twin of the local slot list (4 slots per player, one ACTIVE).
-- cards is the {card-id: copies} map, exactly what the deck code encodes; key_card is the
-- Aeterna house rule Key Spirit (one Spirit card per deck).
CREATE TABLE IF NOT EXISTS deck_slots (
  id          uuid PRIMARY KEY,
  account_id  uuid NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
  slot        smallint NOT NULL CHECK (slot BETWEEN 1 AND 8),
  name        text NOT NULL CHECK (length(name) BETWEEN 1 AND 60),
  format      text NOT NULL DEFAULT 'standard' CHECK (format IN ('standard', 'eternal')),
  cards       jsonb NOT NULL,
  key_card    text,
  sleeve      jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (account_id, slot)
);
CREATE INDEX IF NOT EXISTS deck_slots_account_idx ON deck_slots (account_id);

-- A match, as the room host ran it. seed plus both decks is what makes a record replayable.
CREATE TABLE IF NOT EXISTS matches (
  id          uuid PRIMARY KEY,
  room_code   text,
  format      text NOT NULL CHECK (format IN ('standard', 'eternal')),
  seed        bigint NOT NULL,
  deck_a      jsonb NOT NULL,
  deck_b      jsonb NOT NULL,
  key_a       text,
  key_b       text,
  build       text NOT NULL,                                   -- the engine VERSION that played it
  winner      text CHECK (winner IN ('player', 'opponent')),
  turns       integer CHECK (turns >= 0),
  started_at  timestamptz NOT NULL DEFAULT now(),
  ended_at    timestamptz
);
CREATE INDEX IF NOT EXISTS matches_ended_idx ON matches (ended_at DESC NULLS LAST);
CREATE INDEX IF NOT EXISTS matches_room_idx ON matches (room_code) WHERE room_code IS NOT NULL;

-- One row per seat. account_id stays NULL for a guest, which is why display_name is duplicated
-- here: a match keeps the name it was played under even if the account is deleted.
CREATE TABLE IF NOT EXISTS match_seats (
  match_id      uuid NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
  seat          text NOT NULL CHECK (seat IN ('player', 'opponent')),
  account_id    uuid REFERENCES accounts (id) ON DELETE SET NULL,
  display_name  text NOT NULL CHECK (length(display_name) BETWEEN 1 AND 40),
  is_bot        boolean NOT NULL DEFAULT false,
  PRIMARY KEY (match_id, seat)
);
CREATE INDEX IF NOT EXISTS match_seats_account_idx ON match_seats (account_id) WHERE account_id IS NOT NULL;

-- The replay itself: the port record v2 (decisions included) and the log hash it must reproduce.
-- Kept in its own table because it is large and only read when someone opens the replay.
CREATE TABLE IF NOT EXISTS match_replays (
  match_id   uuid PRIMARY KEY REFERENCES matches (id) ON DELETE CASCADE,
  record     jsonb NOT NULL,
  log_hash   text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMIT;
