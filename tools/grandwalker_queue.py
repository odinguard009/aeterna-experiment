#!/usr/bin/env python3
"""Lane K Grandwalker work queue (owner, 2026-11-04): Nexus whose own families hold 50 cards or fewer (SD44+, pool families not counted) come first, newest to oldest;
Nexus with more than 50 come after them, again newest to oldest. A Nexus is done when all its own-family cards are complete.
Reads data/kb/grandwalker-nexus.json (run tools/grandwalker_data.py first). Writes docs/reports/grandwalker-queue.md; prints the next open Nexus."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
POOL = {'起幻', '天渡', '剣獣', '機獣', '原初'}   # plan 2a.6: five big shared families, not counted toward a Nexus
LIMIT = 50
d = json.load(open(root / 'data/kb/grandwalker-nexus.json', encoding='utf8'))
rows = []
for pos, n in enumerate(d['nexus']):                 # file order = newest first
    fams = [f for f in n['own_families_jp'] if f not in POOL]
    cards = {c['id']: c['complete'] for f in fams for c in d['family_cards'].get(f, [])}
    names = ', '.join(d['family_en'].get(f, f) for f in fams) or '(pool or cost-only: Nexus card only)'
    rows.append(dict(pos=pos, id=n['id'], name=n['name_en'], fams=names, total=len(cards), done=sum(cards.values())))
tier = lambda r: 0 if r['total'] <= LIMIT else 1
rows.sort(key=lambda r: (tier(r), r['pos']))
out = ['# Lane K Grandwalker queue (generated by `tools/grandwalker_queue.py`, do not edit)', '',
       f'Rule (owner 2026-11-04): Nexus with {LIMIT} or fewer own-family cards (SD44+, pool families not counted) first, then the larger ones; inside each group newest to oldest. Open = not all own-family cards complete.', '',
       '| Order | Group | Grandwalker Nexus | Own families | Cards SD44+ | Complete | State |', '|--:|---|---|---|--:|--:|---|']
nxt = None
for i, r in enumerate(rows, 1):
    st = 'done' if r['done'] == r['total'] else 'open'
    if st == 'open' and nxt is None: nxt = r
    out.append(f"| {i} | {'small' if tier(r)==0 else 'large'} | {r['id']} {r['name']} | {r['fams']} | {r['total']} | {r['done']} | {st} |")
(root / 'docs/reports/grandwalker-queue.md').write_text('\n'.join(out) + '\n', encoding='utf8')
print('next open Nexus:', f"{nxt['id']} {nxt['name']} ({nxt['done']}/{nxt['total']})" if nxt else 'none')
