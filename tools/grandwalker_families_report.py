#!/usr/bin/env python3
"""Report of every Grandwalker Nexus with its own families, card counts (SD44+, i.e. after SD43/SD44 release 2018-04-07) and the complete cards.
Reads data/kb/grandwalker-nexus.json (run tools/grandwalker_data.py first). Writes docs/reports/grandwalker-family-cards.md."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
d = json.load(open(root / 'data/kb/grandwalker-nexus.json', encoding='utf8'))
POOL = {'起幻', '天渡', '剣獣', '機獣', '原初'}
en = d['family_en']
fam_rows = {}
for f, cs in d['family_cards'].items():
    fam_rows[f] = (len(cs), [c for c in cs if c['complete']])
out = ['# Grandwalker Nexus, families and complete cards (generated by `tools/grandwalker_families_report.py`, do not edit)', '',
       'Counts are library cards of BS44+/SD44+ (released after SD43/SD44, 7 April 2018) per family. A card is complete when every printed effect runs.', '',
       '## Nexus table', '', '| Nexus | Name | Kind | Own families | Cards | Complete |', '|---|---|---|---|--:|--:|']
for n in d['nexus']:
    fams = n['own_families_jp']
    t = sum(fam_rows.get(f, (0, []))[0] for f in fams if f not in POOL)
    c = sum(len(fam_rows.get(f, (0, []))[1]) for f in fams if f not in POOL)
    out.append(f"| {n['id']} | {n['name_en']} | {n['kind']} | {', '.join(en.get(f, f) for f in fams) or '-'} | {t} | {c} |")
out += ['', '## Family totals', '', '| Family | JP | Cards | Complete |', '|---|---|--:|--:|']
for f, (t, c) in sorted(fam_rows.items(), key=lambda kv: -kv[1][0]):
    out.append(f"| {en.get(f, f)} | {f} | {t} | {len(c)} |")
out += ['', '## Complete cards per family', '']
for f, (t, c) in sorted(fam_rows.items(), key=lambda kv: en.get(kv[0], kv[0])):
    if not c: continue
    out.append(f"### {en.get(f, f)} ({f}): {len(c)}/{t}")
    out.append('; '.join(f"{x['id']} {x['name']}" for x in c))
    out.append('')
(root / 'docs/reports/grandwalker-family-cards.md').write_text('\n'.join(out) + '\n', encoding='utf8')
print(len(fam_rows), 'families,', sum(len(v[1]) for v in fam_rows.values()), 'complete family-card entries')
