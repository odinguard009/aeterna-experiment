#!/usr/bin/env python3
"""Residual blocker tags (card-session prep): classify every partial card's residual clauses with the glossary
patterns and rank the blockers by how many cards they keep incomplete, straight from the residual data (no recompile).

  python3 tools/residual_tags.py          -> writes data/glossary/residual-tags.json + docs/reports/residual-blockers.md
  python3 tools/residual_tags.py --line   -> summary line only (used by session tooling)
  python3 tools/residual_tags.py --check  -> exit 1 when residual-tags.json differs from a fresh computation

Why: `residual` is free text, so "which blocker keeps how many cards incomplete" used to be re-derived by re-compiling
the text. This tool gives that signal directly. Patterns are hints for a human, not a parser (same caveat as
tools/tag_effects.py): always read the clause before wiring, and correctness is never decided here.
"""
import json, os, re, sys, collections
import allcards      # build/all-cards.json is generated (not in git): allcards.load() writes it when missing or stale

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
J = lambda p: json.load(open(os.path.join(root, p), encoding='utf8'))
gl = J('data/glossary/effects.json')
rx = [(g, re.compile(g['pattern'])) for g in gl]
by = {g['id']: g for g in gl}
cards = allcards.load()

RT_PATH = os.path.join(root, 'data/glossary/residual-tags.json')


def compute():
    rt = {}                                   # card id -> sorted tag ids (union over its residual clauses; present even when empty)
    use_cards = collections.defaultdict(int)  # tag -> cards whose residual mentions it
    use_cl = collections.defaultdict(int)     # tag -> clauses mentioning it
    unclassified = collections.defaultdict(int)  # card id -> clauses no glossary tag matched
    total_clauses = 0
    for c in cards:
        res = c.get('residual') or []
        if not res:
            continue
        tags = set()
        for cl in res:
            total_clauses += 1
            hit = [g['id'] for g, r in rx if r.search(cl)]
            if not hit:
                unclassified[c['id']] += 1
            tags.update(hit)
            for x in hit:
                use_cl[x] += 1
        rt[c['id']] = sorted(tags)
        for x in tags:
            use_cards[x] += 1
    return rt, use_cards, use_cl, unclassified, total_clauses


def main():
    rt, use_cards, use_cl, unclassified, total_clauses = compute()
    classified = total_clauses - sum(unclassified.values())
    if '--check' in sys.argv:
        cur = None
        try:
            cur = json.load(open(RT_PATH, encoding='utf8'))
        except Exception:
            cur = None
        if cur != rt:
            print('residual-tags.json is out of date: run  python3 tools/residual_tags.py')
            sys.exit(1)
        print('residual-tags.json up to date')
        return 0
    line = (f'residual blockers: {len(rt)} partial cards, {total_clauses} clauses, {len(use_cards)} distinct tags '
            f'({classified} classified, {sum(unclassified.values())} unclassified)')
    if '--line' in sys.argv:
        print(line)
        return 0
    json.dump(rt, open(RT_PATH, 'w', encoding='utf8', newline=''), indent=1)
    L = ['# Residual blockers (generated by tools/residual_tags.py; do not edit)', '',
         f'**{line}.** Classified by the glossary patterns over each residual clause; the clauses are what does not run yet.',
         'Patterns are hints, not a parser: always read the clause before wiring.', '',
         '## Blockers (partial / missing tags) by residual cards', '',
         '| Tag | Status | Cards | Clauses | Meaning |', '|---|---|---|---|---|']
    for tag, n in sorted(use_cards.items(), key=lambda kv: (-kv[1], -use_cl[kv[0]])):
        if by[tag]['status'] == 'wired':
            continue
        L.append(f"| {tag} | {by[tag]['status']} | {n} | {use_cl[tag]} | {by[tag]['meaning'][:80]} |")
    L += ['', f'## Unclassified residual clauses ({sum(unclassified.values())}): no glossary pattern matches yet',
          '',
          'The tail that needs a new glossary tag / mechanic. Top cards by unclassified clauses:', '']
    top = sorted(unclassified.items(), key=lambda kv: -kv[1])[:15]
    for cid, n in top:
        L.append(f'- {cid}: {n}')
    L += ['', '## All mentioned tags (hints, wired included)', '',
          'Wired tags like the level heads (`C_LEVEL`) and `M_OPTIONAL` (`You can`) are structural prefixes the clause',
          'keeps, not the blocker itself; the actionable list is the "Blockers" section above.',
          '',
          '| Tag | Status | Cards | Clauses | Meaning |', '|---|---|---|---|---|']
    for tag, n in sorted(use_cards.items(), key=lambda kv: (-kv[1], -use_cl[kv[0]])):
        L.append(f"| {tag} | {by[tag]['status']} | {n} | {use_cl[tag]} | {by[tag]['meaning'][:80]} |")
    open(os.path.join(root, 'docs/reports/residual-blockers.md'), 'w', encoding='utf8', newline='').write('\n'.join(L) + '\n')
    print(line, '->', 'data/glossary/residual-tags.json, docs/reports/residual-blockers.md')
    return 0


if __name__ == '__main__':
    sys.exit(main())
