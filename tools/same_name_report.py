#!/usr/bin/env python3
"""List cards that share a name but are different cards (different serial and different game data).
Usage: python3 tools/same_name_report.py [--out docs/reports/same-name-cards.md]
Same-name cards are NOT merged by the data layer (ids are serial numbers); the UI and importers must not merge them either."""
import glob, json, re, sys, collections

def norm(t):
    t = (t or '').lower().replace('‘', "'").replace('’', "'").replace('“', '"').replace('”', '"')
    return re.sub(r'\s+', ' ', re.sub('[‐-―]', '-', t)).strip()

def sig(c):
    return json.dumps([c.get('type'), c.get('color'), c.get('cost'), c.get('symbols'), c.get('reduction'), c.get('levels'), c.get('families'), norm(c.get('text'))], sort_keys=True)

by = collections.defaultdict(dict)
for root in ('data/cards', 'data/import'):
    for f in sorted(glob.glob(root + '/saga-*.json')):
        for c in json.load(open(f)):
            if not c.get('token'):
                by[c['name']].setdefault(c['id'], c)
rows = []
for name, ids in sorted(by.items()):
    groups = collections.defaultdict(list)
    for i, c in ids.items():
        groups[sig(c)].append(i)
    if len(groups) > 1:
        rows.append((name, [sorted(g) for g in groups.values()]))
out = ['# Same name, different cards', '', f'{len(rows)} names are shared by cards with different data (generated by `tools/same_name_report.py`).', '']
for name, gs in rows:
    out.append(f'- **{name}**: ' + ' | '.join(', '.join(g) for g in gs))
text = '\n'.join(out) + '\n'
if '--out' in sys.argv:
    open(sys.argv[sys.argv.index('--out') + 1], 'w').write(text)
print(f'{len(rows)} names with different cards')
