// Port the stylesheet of docs/design/mockup-v14.html into apps/web/mockup.css, scoped under .mk (owner, 2026-10-26: "tinggal meniru
// mockup": the web game must match the mockup in fonts, sizes and placement, so its CSS is taken from the mockup, not re-guessed).
//   node tools/port_mockup_css.mjs          writes apps/web/mockup.css
//   node tools/port_mockup_css.mjs --check  exits 1 when the file is stale
// The mockup sizes everything in em from the .frame font size and switches PC / phone with a container query on the .frame; the game's
// root wrapper .mk takes that role (container fr). Colour variables the game's theme owns (--you, --you-ink, --you-soft, --cpu) are
// dropped from the variable blocks so the saved side colour keeps working.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const SRC = 'docs/design/mockup-v14.html', OUT = 'apps/web/mockup.css';
const html = readFileSync(SRC, 'utf8');
const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).sort((a, b) => b.length - a.length)[0].replace(/\/\*[\s\S]*?\*\//g, '');

function blocks(s) {                      // [{head, body}] at one nesting level
  const out = []; let i = 0;
  while (i < s.length) {
    const o = s.indexOf('{', i); if (o < 0) break;
    let d = 1, j = o + 1;
    while (j < s.length && d) { if (s[j] === '{') d++; else if (s[j] === '}') d--; j++; }
    out.push({ head: s.slice(i, o).trim(), body: s.slice(o + 1, j - 1) }); i = j;
  }
  return out;
}
const GAME_VARS = /--(you|you-ink|you-soft|cpu)\s*:[^;]+;?/g;
function scopeSel(sel) {
  sel = sel.trim(); if (!sel) return null;
  if (/^(html|body)$/.test(sel)) return '.mk';
  if (sel === '*') return '.mk *';
  if (sel.includes('.frame[data-dev')) return null;           // the device switch of the mockup has no meaning in the game
  let m;
  if ((m = sel.match(/^:root\[data-mode="light"\](.*)$/))) return `[data-mode="light"] .mk${m[1]}`;
  if (sel === ':root') return '.mk';
  if (sel.startsWith('.frame')) return '.mk' + sel.slice(6);
  return '.mk ' + sel;
}
function scopeRules(src) {
  let out = '';
  for (const b of blocks(src)) {
    if (/^@(container|media|supports)/.test(b.head)) { const inner = scopeRules(b.body); if (inner) out += `${b.head}{${inner}}\n`; continue; }
    if (/^@keyframes/.test(b.head)) { out += `${b.head.replace('@keyframes ', '@keyframes mk-')}{${b.body}}\n`; continue; }
    if (b.head.startsWith('@')) { out += `${b.head}{${b.body}}\n`; continue; }
    const sels = b.head.split(',').map(scopeSel).filter(Boolean);
    let body = b.body;
    if (/^(:root|:root\[data-mode="light"\])$/.test(b.head.trim())) body = body.replace(GAME_VARS, '');
    if (sels.length && body.trim()) out += `${sels.join(',')}{${body.trim()}}\n`;
  }
  return out;
}
let res = scopeRules(css);
res = res.replace(/animation(-name)?:\s*([a-zA-Z]+)/g, (all, n, name) => (/^(none|inherit|initial)$/.test(name) ? all : `animation${n || ''}:mk-${name}`));
res = res.replace(/(\.mk\{[^}]*?)height:800px/, '$1height:100%');   // the mockup frame is a fixed 800 px preview; the game fills the window
const text = `/* GENERATED by tools/port_mockup_css.mjs from docs/design/mockup-v14.html: never edit by hand. */\n${res}`;
if (process.argv.includes('--check')) { const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''; if (cur !== text) { console.error(`${OUT} is out of date: run node tools/port_mockup_css.mjs`); process.exit(1); } console.log(`${OUT} matches the mockup`); }
else { writeFileSync(OUT, text); console.log(`wrote ${OUT}: ${text.length} bytes, ${res.split('\n').length} rules`); }
