#!/usr/bin/env python3
"""Lane K priority list (owner, 2026-11-04): a STANDING list of card groups in data/kb/lane-k-priority.json. Groups are worked top to bottom
BEFORE the Grandwalker queue; a group whose cards are all complete is skipped (kept as history, never reused). "Complete" = tools/card_counts.py.
  python3 tools/priority_queue.py                      print progress + the next open cards, write docs/reports/lane-k-priority.md
  python3 tools/priority_queue.py --add ID --title T [--ids A,B] [--families F1,F2] [--nexus NEXUSID] [--note N] [--top | --after GROUPID]
                                                       add a group (default: bottom); select = ids and/or families (English) and/or a Grandwalker Nexus (Nexus card + deck cards)
  python3 tools/priority_queue.py --remove ID          drop a group (owner asked to cancel it)
Always exits 0 in print mode (session_start calls it)."""
import argparse, json, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / 'tools'))
PRI = root / 'data/kb/lane-k-priority.json'
ap = argparse.ArgumentParser()
ap.add_argument('--add'); ap.add_argument('--remove'); ap.add_argument('--title', default=''); ap.add_argument('--ids', default='')
ap.add_argument('--families', default=''); ap.add_argument('--nexus', default=''); ap.add_argument('--note', default='')
ap.add_argument('--top', action='store_true'); ap.add_argument('--after', default='')
a = ap.parse_args()
pri = json.load(open(PRI, encoding='utf8'))
G = pri['groups']
if a.add or a.remove:
    if a.remove:
        G[:] = [g for g in G if g['id'] != a.remove]
    else:
        if any(g['id'] == a.add for g in G): sys.exit(f'group {a.add} exists')
        sel = {}
        if a.ids: sel['ids'] = [x.strip() for x in a.ids.split(',') if x.strip()]
        if a.families: sel['families'] = [x.strip() for x in a.families.split(',') if x.strip()]
        if a.nexus: sel['nexus'] = a.nexus
        if not sel: sys.exit('give --ids, --families or --nexus')
        import datetime
        g = {'id': a.add, 'title': a.title or a.add, 'added': datetime.date.today().isoformat(), 'note': a.note, 'select': sel}
        if a.top: G.insert(0, g)
        elif a.after:
            i = next((k for k, x in enumerate(G) if x['id'] == a.after), None)
            if i is None: sys.exit(f'no group {a.after}')
            G.insert(i + 1, g)
        else: G.append(g)
    json.dump(pri, open(PRI, 'w', encoding='utf8'), indent=1, ensure_ascii=False); (open(PRI, 'a').write('\n'))
import card_counts, allcards
cards = {c['id']: c for c in allcards.load()}
gw = json.load(open(root / 'data/kb/grandwalker-nexus.json', encoding='utf8'))['nexus']
def resolve(sel):
    ids = list(sel.get('ids', []))
    for fam in sel.get('families', []):
        ids += sorted(i for i, c in cards.items() if fam in (c.get('families') or []))
    if sel.get('nexus'):
        n = next((x for x in gw if x['id'] == sel['nexus']), None)
        ids += [sel['nexus']] + (list(n['deck_cards']) if n else [])
    seen, out = set(), []
    for i in ids:
        if i not in seen: seen.add(i); out.append(i)
    return out
claimed, rows, lines = set(), [], []
for g in G:
    ids = [i for i in resolve(g['select']) if i not in claimed]   # a card belongs to the first group that names it
    claimed.update(ids)
    st = [(i, (cards[i]['name'] if i in cards else '(not in data)'), (card_counts.complete(cards[i]) if i in cards else False)) for i in ids]
    g['_st'] = st
open_groups = [g for g in G if any(not ok for _, _, ok in g['_st'])]
out = ['# Lane K priority list (generated by `tools/priority_queue.py`, do not edit)', '',
       'Standing list (owner 2026-11-04): groups top to bottom, all before the Grandwalker queue. Edit data/kb/lane-k-priority.json with the tool (`--add`, `--top`, `--after`, `--remove`).', '']
for n, g in enumerate(G, 1):
    st = g['_st']; done = sum(ok for _, _, ok in st)
    out += [f'## {n}. {g["title"]} ({g["id"]}): {done} of {len(st)} complete' + (' - DONE' if done == len(st) else ''), f'Added {g["added"]}. {g.get("note","")}', '']
    if done != len(st): out += ['| Card | Name | State |', '|---|---|---|'] + [f'| {i} | {nm} | OPEN |' for i, nm, ok in st if not ok] + ['']
pathlib.Path(root / 'docs/reports/lane-k-priority.md').write_text('\n'.join(out), encoding='utf8')
tot = sum(len(g['_st']) for g in G); dn = sum(ok for g in G for _, _, ok in g['_st'])
print(f'priority list: {dn}/{tot} complete in {len(G)} groups; ' + (f'working "{open_groups[0]["id"]}" ({sum(ok for _,_,ok in open_groups[0]["_st"])}/{len(open_groups[0]["_st"])}), next open: ' + ', '.join(i for i, _, ok in open_groups[0]['_st'] if not ok)[:120] if open_groups else 'ALL DONE, Grandwalker queue resumes'))
for g in G: print(f'  {g["id"]}: {sum(ok for _,_,ok in g["_st"])}/{len(g["_st"])}')
print('K ORDER (owner 2026-11-05): take the next open card of the FIRST open group above; the Grandwalker queue (tools/grandwalker_queue.py) is used only when every group is complete.' if open_groups else 'K ORDER: priority list complete -> now the Grandwalker queue (python3 tools/grandwalker_queue.py)')
