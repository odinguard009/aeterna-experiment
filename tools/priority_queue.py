#!/usr/bin/env python3
"""Lane K priority list (owner, 2026-11-04): the cards in data/kb/lane-k-priority.json are worked before the Grandwalker queue until all are complete.
Prints done/open counts and the open ids; writes docs/reports/lane-k-priority.md. Exit 0 always (session_start calls it)."""
import json, glob, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
pri = json.load(open(root / 'data/kb/lane-k-priority.json', encoding='utf8'))
state = {}
for f in sorted(glob.glob(str(root / 'data/cards/saga-*.json'))):
    d = json.load(open(f, encoding='utf8'))
    if isinstance(d, dict): d = d.get('cards', list(d.values()))
    for c in d: state[c['id']] = bool(c.get('fxComplete'))
rows = [(c['id'], c['name'], state.get(c['id'])) for c in pri['cards']]
done = sum(1 for r in rows if r[2]); open_ = [r for r in rows if not r[2]]
lines = ['# Lane K priority list (generated by `tools/priority_queue.py`, do not edit)', '',
         f'Owner order {pri["owner_order"]}: these {len(rows)} cards come before the Grandwalker queue. Complete {done} of {len(rows)}.', '',
         '| Card | Name | State |', '|---|---|---|'] + [f'| {i} | {n} | {"complete" if ok else ("OPEN" if ok is False else "missing from data")} |' for i, n, ok in rows]
(root / 'docs/reports/lane-k-priority.md').write_text('\n'.join(lines) + '\n', encoding='utf8')
print(f'priority list: {done}/{len(rows)} complete; ' + (f'next {len(open_)} open, first: ' + ', '.join(r[0] for r in open_[:6]) if open_ else 'DONE, Grandwalker queue resumes'))
