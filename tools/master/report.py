#!/usr/bin/env python3
"""Writes docs/reports/master-import.md from the master database and the library: counts, skipped cards,
library-vs-official cost / BP mismatches, source conflicts, English gaps.  python3 tools/master/report.py"""
import gzip, json, glob, os, collections
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
M = json.load(gzip.open(os.path.join(R, 'data/master/cards.json.gz')))
lib = {c['id']: c for f in glob.glob(os.path.join(R, 'data/cards/saga-[0-9][0-9].json')) for c in json.load(open(f, encoding='utf-8'))}
cls = collections.Counter(r['class'] for r in M.values())
cost, bp, pend_n, pend_t = [], [], [], []
for i, c in lib.items():
    r = M.get(i)
    if not r or 'official' not in r['sources']: continue
    if r.get('cost') is not None and c['type'] != 'Magic' and c['cost'] != r['cost']: cost.append((i, c['cost'], r['cost']))
    if c['type'] in ('Spirit', 'Ultimate'):
        a = [l.get('bp') for l in c['levels']]; b = [l.get('bp') for l in r.get('levels') or [] if l.get('bp') is not None]
        if a != b and not (len(b) > len(a) and b[:len(a)] == a): bp.append((i, a, b))
    n = c.get('note', '')
    if 'English name pending' in n: pend_n.append(i)
    if 'English text pending' in n: pend_t.append(i)
L = ['# Master import report (generated by tools/master/report.py)', '',
     f'Master database: {len(M)} card numbers; library: {len(lib)} cards.', '',
     '## Classification', *[f'- {k}: {v}' for k, v in cls.most_common()], '',
     '## Not imported', '- stubs (Fandom row with no card data): ' + ', '.join(sorted(i for i, r in M.items() if r['class'] == 'stub')),
     '- tokens (cannot be put in a deck): ' + ', '.join(sorted(i for i, r in M.items() if r['class'] == 'token')), '',
     f'## English still pending: {len(pend_n)} names, {len(pend_t)} texts', '(card ids: ' + ', '.join(sorted(pend_n)[:2000]) + ')', '',
     f'## Library vs official data (library kept, owner decision: hand-verified data wins): {len(cost)} cost differences, {len(bp)} BP differences',
     *[f'- {i}: library cost {a}, official {b}' for i, a, b in sorted(cost)], '',
     *[f'- {i}: library BP {a}, official {b}' for i, a, b in sorted(bp)], '',
     f'## Source conflicts recorded in the master: {sum(1 for r in M.values() if r.get("conflicts"))} cards (field `conflicts`)']
open(os.path.join(R, 'docs/reports/master-import.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(len(cost), len(bp), len(pend_n), len(pend_t))
