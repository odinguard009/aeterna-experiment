#!/usr/bin/env node
// Generates docs/ai/code-map.md: which src part owns which top-level names, with size in tokens.
// Read the map instead of exploring the code. Kept current by `node tools/build.mjs` and checked by test B13.
//   node tools/code_map.mjs          -> writes docs/ai/code-map.md
//   node tools/code_map.mjs --print  -> prints it
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { srcParts } from './src_parts.mjs';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export function codeMap() {
  const parts = srcParts(ROOT);
  const rows = parts.map(p => {
    const s = readFileSync(join(ROOT, p.rel), 'utf8').replace(/\r\n/g, '\n');      // LF length, so a Windows CRLF checkout gives the same map as CI
    const names = [...s.matchAll(/^(?:async\s+)?(?:function\s+([\w$]+)|(?:const|let|var|class)\s+([\w$]+))/gm)].map(m => m[1] || m[2]);
    const L = s.split('\n'), title = /^\/\* -{5,}/.test(L[0]) && /^\s{3}\S/.test(L[1] || '') ? L[1].trim().split(/\s{2,}/)[0] : '';
    return `## ${p.rel} (${s.split('\n').length - 1} lines, ~${Math.round(s.length / 4 / 100) / 10}k tokens)${title ? ' — ' + title.trim() : ''}\n${names.join(', ')}\n`;
  });
  return '# Code map (generated by tools/code_map.mjs — do not edit)\n\nTop-level names per source part. Find the part here, then `grep -n "<name>" <part path>` and read only that range.\n\n' + rows.join('\n');
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const md = codeMap();
  if (process.argv.includes('--print')) process.stdout.write(md);
  else { mkdirSync(join(ROOT, 'docs/ai'), { recursive: true }); writeFileSync(join(ROOT, 'docs/ai/code-map.md'), md); console.log(`docs/ai/code-map.md: ~${Math.round(md.length / 4)} tokens`); }
}
