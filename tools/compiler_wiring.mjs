#!/usr/bin/env node
// Compiler wiring report (card-session prep): engine actions that no card-text compiler can emit ("hand-write only").
//   node tools/compiler_wiring.mjs          -> writes docs/reports/compiler-wiring.md
//   node tools/compiler_wiring.mjs --check  -> exit 1 when the report differs from a fresh computation
// Reads packages/engine/fx-schema.json (the actions) and scans tools/compile_effects.py (v1) + tools/compile_v2.py (v2)
// for each action name as a quoted literal ('NAME' / "NAME"). The compilers emit `{'do': 'NAME', ...}`, so a quoted
// occurrence is an emission in practice. This is a hint for a card session, not a parser: correctness is never decided
// here, and structural wrappers (BY, the `_THEN` chains) are hand-written by design.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPORT = join(ROOT, 'docs/reports/compiler-wiring.md');

function compute() {
  const schema = JSON.parse(readFileSync(join(ROOT, 'packages/engine/fx-schema.json'), 'utf8'));
  const actions = Object.keys(schema.actions).sort();
  const both = readFileSync(join(ROOT, 'tools/compile_effects.py'), 'utf8')
    + '\n' + readFileSync(join(ROOT, 'tools/compile_v2.py'), 'utf8');
  const emitted = actions.filter((a) => new RegExp(`['"]${a}['"]`).test(both));
  const hand = actions.filter((a) => !emitted.includes(a));
  return { actions, emitted, hand };
}

function report({ actions, emitted, hand }) {
  const list = (arr) => arr.length ? arr.map((a) => `- \`${a}\``).join('\n') : '- (none)';
  const L = ['# Compiler wiring (generated by tools/compiler_wiring.mjs; do not edit)', '',
    `The engine has ${actions.length} actions (\`packages/engine/fx-schema.json\`). The two card-text compilers`,
    '(`tools/compile_effects.py` v1 + `tools/compile_v2.py` v2) emit ' + emitted.length + ' of them; the rest are written by hand.', '',
    '## Hand-write only (no compiler pattern)', '', list(hand), '',
    '## Emitted by a compiler', '', list(emitted), '',
    'Notes: this is a hint for a card session, not a parser. Structural wrappers (`BY`, the `_THEN` chains) and actions',
    'that only appear in complex shapes are hand-written by design. Correctness is never decided here — a compiled card',
    'still passes `tools/fx_validate.mjs` and `python3 tools/card_verify.py <id>` against the source text before promotion.'];
  return L.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const r = report(compute());
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(REPORT, 'utf8'); } catch { /* missing */ }
    if (cur !== r) { console.error('docs/reports/compiler-wiring.md is out of date: run  node tools/compiler_wiring.mjs'); process.exit(1); }
    console.log('docs/reports/compiler-wiring.md up to date');
  } else {
    writeFileSync(REPORT, r);
    const { emitted, hand } = compute();
    console.log(`compiler wiring: ${emitted.length} of ${emitted.length + hand.length} actions emitted, ${hand.length} hand-write only -> docs/reports/compiler-wiring.md`);
  }
}
